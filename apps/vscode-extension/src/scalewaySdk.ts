import { Buffer } from 'node:buffer';
import * as https from 'node:https';
import { createAdvancedClient, withHTTPClient } from '@scaleway/sdk-client';
import { Iamv1alpha1 } from '@scaleway/sdk-iam';
import { Inferencev1 } from '@scaleway/sdk-inference';

// SDK logging is silent by default; never enable it for credential responses.
export class SDKError extends Error {
  constructor(public code: string) {
    super(code);
  }
}
const uuid = (v: unknown): v is string =>
  typeof v === 'string' &&
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(v);
const jwt = (v: string) =>
  v.length <= 16384 &&
  /^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(v);
const accessKey = (v: unknown): v is string =>
  typeof v === 'string' && /^SCW[A-Z0-9]{17}$/.test(v);
export const API_KEY_DESCRIPTION =
  'Generated by Scaleway AI Toolkit for VS Code';
export const API_KEY_LIFETIME_MS = 30 * 24 * 60 * 60 * 1000;
const client = (http: typeof fetch) =>
  createAdvancedClient(withHTTPClient(http));
const sameURL = (a: URL, b: URL) => {
  a.searchParams.sort();
  b.searchParams.sort();
  return a.href === b.href;
};

/** Invoke exactly one official SDK read and retain raw JSON for strict local parsers.
 * Generated unmarshallers default missing fields; their output is NOT validation.
 * The callback must provide the provider's bounded, authenticated HTTPS transport.
 */
export async function readDedicatedJSON(
  path: string,
  signal: AbortSignal,
  send: (path: string) => Promise<unknown>,
): Promise<unknown> {
  if (signal.aborted) throw new SDKError('cancelled');
  const url = new URL(path, 'https://api.scaleway.com');
  const base = '/inference/v1/regions/fr-par/';
  const route = url.pathname.slice(base.length);
  const detail =
    /^deployments\/[0-9a-f-]{36}$/i.test(route) && uuid(route.split('/')[1]);
  const node = route === 'node-types';
  const fields = node
    ? ['include_disabled_types', 'page', 'page_size']
    : ['organization_id', 'project_id', 'page', 'page_size'];
  const list =
    ['models', 'deployments', 'node-types'].includes(route) &&
    url.searchParams.size === fields.length &&
    fields.every((f) => url.searchParams.getAll(f).length === 1) &&
    /^[1-5]$/.test(url.searchParams.get('page') ?? '') &&
    url.searchParams.get('page_size') === '100' &&
    (node
      ? url.searchParams.get('include_disabled_types') === 'true'
      : uuid(url.searchParams.get('organization_id')) &&
        uuid(url.searchParams.get('project_id')));
  if (
    url.origin !== 'https://api.scaleway.com' ||
    url.username ||
    url.password ||
    url.hash ||
    !url.pathname.startsWith(base) ||
    !(list || (detail && !url.search))
  )
    throw new SDKError('invalid_request');
  let captured = false;
  let raw: unknown;
  const http: typeof fetch = async (input, init) => {
    const request = input instanceof Request ? input : new Request(input, init);
    const actual = new URL(request.url);
    if (
      captured ||
      request.method !== 'GET' ||
      !sameURL(new URL(url.href), new URL(actual.href))
    )
      throw new SDKError('invalid_request');
    raw = await send(actual.pathname + actual.search);
    captured = true;
    return new Response(JSON.stringify(raw), {
      headers: { 'Content-Type': 'application/json' },
    });
  };
  const api = new Inferencev1.API(client(http));
  const options = { signal };
  const scope = {
    region: 'fr-par' as const,
    page: Number(url.searchParams.get('page')),
    pageSize: 100,
    organizationId: url.searchParams.get('organization_id') ?? undefined,
    projectId: url.searchParams.get('project_id') ?? undefined,
  };
  try {
    if (detail)
      await api.getDeployment(
        { region: 'fr-par', deploymentId: route.split('/')[1] },
        options,
      );
    else if (node)
      await api.listNodeTypes(
        {
          region: 'fr-par',
          page: scope.page,
          pageSize: 100,
          includeDisabledTypes: true,
        },
        options,
      );
    else if (route === 'models') await api.listModels(scope, options);
    else await api.listDeployments(scope, options);
  } catch (error) {
    // Only tolerate generated normalization failures AFTER successful raw receipt.
    // Transport failures propagate without SDK response bodies/context.
    if (!captured) {
      if (error instanceof Error && 'code' in error) throw error;
      throw new SDKError('transport_error');
    }
  }
  if (signal.aborted) throw new SDKError('cancelled');
  if (!captured) throw new SDKError('invalid_response');
  return raw;
}

/** Bounded IAM-only transport. No general write-capable SDK client is exported. */
export const boundedIAMHTTP: typeof fetch = async (input, init) => {
  const request = input instanceof Request ? input : new Request(input, init);
  const url = new URL(request.url);
  const token = request.headers.get('X-Session-Token') ?? '';
  const secret = request.headers.get('X-Auth-Token') ?? '';
  const keyRead =
    request.method === 'GET' &&
    url.pathname ===
      '/iam/v1alpha1/api-keys/' + url.pathname.split('/').at(-1) &&
    accessKey(url.pathname.split('/').at(-1));
  if (
    url.origin !== 'https://api.scaleway.com' ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    !(keyRead ? uuid(secret) && !token : jwt(token) && !secret) ||
    !(
      keyRead ||
      (request.method === 'POST' &&
        url.pathname === '/iam/v1alpha1/api-keys') ||
      (request.method === 'DELETE' &&
        /^\/iam\/v1alpha1\/api-keys\/SCW[A-Z0-9]{17}$/.test(url.pathname))
    )
  )
    throw new SDKError('invalid_request');
  const body = request.method === 'POST' ? await request.text() : undefined;
  if (body !== undefined) {
    let data: Record<string, unknown>;
    try {
      data = JSON.parse(body);
    } catch {
      throw new SDKError('invalid_request');
    }
    if (!data || typeof data !== 'object' || Array.isArray(data))
      throw new SDKError('invalid_request');
    const expires =
      typeof data.expires_at === 'string' ? Date.parse(data.expires_at) : NaN;
    if (
      !uuid(data.user_id) ||
      data.description !== API_KEY_DESCRIPTION ||
      !Number.isFinite(expires) ||
      expires <= Date.now() ||
      expires > Date.now() + API_KEY_LIFETIME_MS ||
      Object.keys(data).sort().join(',') !== 'description,expires_at,user_id'
    )
      throw new SDKError('invalid_request');
  }
  if (request.signal.aborted) throw new SDKError('cancelled');
  return new Promise<Response>((resolve, reject) => {
    let done = false;
    let bytes = 0;
    const chunks: Buffer[] = [];
    const end = (error?: SDKError, response?: Response) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      request.signal.removeEventListener('abort', cancel);
      req.destroy();
      if (error) reject(error);
      else if (response) resolve(response);
    };
    const cancel = () => end(new SDKError('cancelled'));
    const req = https.request(
      {
        hostname: 'api.scaleway.com',
        path: url.pathname,
        method: request.method,
        agent: false,
        headers: {
          Accept: 'application/json',
          'Content-Type': 'application/json',
          ...(keyRead
            ? { 'X-Auth-Token': secret }
            : { 'X-Session-Token': token }),
        },
      },
      (res) => {
        const status = res.statusCode ?? 0;
        if (status < 200 || status > 204) {
          res.destroy();
          return end(
            new SDKError(
              status === 401 && keyRead
                ? 'invalid_api_key'
                : status === 401 || status === 403
                  ? 'access_denied'
                  : status === 429
                    ? 'rate_limited'
                    : status >= 300 && status < 400
                      ? 'redirect_rejected'
                      : 'http_error',
            ),
          );
        }
        if (
          status !== 204 &&
          !res.headers['content-type']?.includes('application/json')
        ) {
          res.destroy();
          return end(new SDKError('invalid_response'));
        }
        res.on('data', (chunk: Buffer) => {
          bytes += chunk.length;
          if (bytes > 2 * 1024 * 1024) {
            res.destroy();
            end(new SDKError('response_limit'));
          } else chunks.push(chunk);
        });
        res.on('error', () => end(new SDKError('transport_error')));
        res.on('aborted', () => end(new SDKError('truncated_response')));
        res.on('end', () => {
          try {
            if (status === 204)
              return end(undefined, new Response(null, { status }));
            const wire = new TextDecoder('utf-8', { fatal: true }).decode(
              Buffer.concat(chunks),
            );
            JSON.parse(wire);
            end(
              undefined,
              new Response(wire, {
                status,
                headers: { 'Content-Type': 'application/json' },
              }),
            );
          } catch {
            end(new SDKError('invalid_response'));
          }
        });
      },
    );
    const timer = setTimeout(() => end(new SDKError('timeout')), 10000);
    req.on('error', () => end(new SDKError('transport_error')));
    request.signal.addEventListener('abort', cancel, { once: true });
    if (request.signal.aborted) return cancel();
    req.end(body);
  });
};

export async function createUserAPIKey(
  userId: string,
  token: string,
  signal: AbortSignal,
): Promise<{ accessKey: string; secretKey: string; expiresAt: number }> {
  if (!uuid(userId) || !jwt(token)) throw new SDKError('invalid_request');
  if (signal.aborted) throw new SDKError('cancelled');
  const requestedExpiry = Date.now() + API_KEY_LIFETIME_MS;
  const http: typeof fetch = (input, init) => {
    const request = input instanceof Request ? input : new Request(input, init);
    request.headers.set('X-Session-Token', token);
    return boundedIAMHTTP(request);
  };
  try {
    const key = await new Iamv1alpha1.API(client(http)).createAPIKey(
      {
        userId,
        description: API_KEY_DESCRIPTION,
        expiresAt: new Date(requestedExpiry),
      },
      { signal },
    );
    const expiresAt = key.expiresAt?.getTime();
    if (
      !accessKey(key.accessKey) ||
      !uuid(key.secretKey) ||
      key.userId !== userId ||
      typeof expiresAt !== 'number' ||
      !Number.isFinite(expiresAt) ||
      expiresAt <= Date.now() ||
      expiresAt > requestedExpiry
    )
      throw new SDKError('invalid_response');
    return { accessKey: key.accessKey, secretKey: key.secretKey, expiresAt };
  } catch (error) {
    if (error instanceof SDKError) throw error;
    throw new SDKError('invalid_response');
  }
}

export async function revokeUserAPIKey(
  key: string,
  token: string,
  signal: AbortSignal,
): Promise<void> {
  if (!accessKey(key) || !jwt(token)) throw new SDKError('invalid_request');
  if (signal.aborted) throw new SDKError('cancelled');
  const http: typeof fetch = (input, init) => {
    const request = input instanceof Request ? input : new Request(input, init);
    request.headers.set('X-Session-Token', token);
    return boundedIAMHTTP(request);
  };
  try {
    await new Iamv1alpha1.API(client(http)).deleteAPIKey(
      { accessKey: key },
      { signal },
    );
  } catch (error) {
    if (error instanceof SDKError) throw error;
    throw new SDKError('invalid_response');
  }
}

/** Exact self-key metadata GET. Never lists keys or returns a server-side secret. */
export async function inspectExistingUserAPIKey(
  access: string,
  secret: string,
  signal: AbortSignal,
): Promise<{ userId: string; accessKey: string; expiresAt: number }> {
  if (!accessKey(access) || !uuid(secret))
    throw new SDKError('invalid_api_key_format');
  if (signal.aborted) throw new SDKError('cancelled');
  let raw: unknown;
  const http: typeof fetch = async (input, init) => {
    const request = input instanceof Request ? input : new Request(input, init);
    if (
      request.method !== 'GET' ||
      request.url !== 'https://api.scaleway.com/iam/v1alpha1/api-keys/' + access
    )
      throw new SDKError('invalid_request');
    request.headers.set('X-Auth-Token', secret);
    const response = await boundedIAMHTTP(request);
    raw = await response.clone().json();
    return response;
  };
  try {
    await new Iamv1alpha1.API(client(http)).getAPIKey(
      { accessKey: access },
      { signal },
    );
    if (!raw || typeof raw !== 'object' || Array.isArray(raw))
      throw new SDKError('invalid_response');
    const row = raw as Record<string, unknown>;
    if (row.access_key !== access) throw new SDKError('invalid_response');
    if (row.application_id) throw new SDKError('application_key_not_supported');
    if (!uuid(row.user_id)) throw new SDKError('invalid_response');
    const expiresAt =
      row.expires_at == null
        ? Number.MAX_SAFE_INTEGER
        : typeof row.expires_at === 'string'
          ? Date.parse(row.expires_at)
          : NaN;
    if (!Number.isFinite(expiresAt)) throw new SDKError('invalid_response');
    if (expiresAt <= Date.now() + 30000) throw new SDKError('api_key_expired');
    return { userId: row.user_id, accessKey: access, expiresAt };
  } catch (error) {
    if (error instanceof SDKError) throw error;
    throw new SDKError('invalid_response');
  }
}
